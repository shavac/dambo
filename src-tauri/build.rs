fn main() {
    let autogenerated_dir = std::path::Path::new("permissions/autogenerated");
    if autogenerated_dir.exists() {
        let _ = std::fs::remove_dir_all(autogenerated_dir);
    }
    let permissions_dir = std::path::Path::new("permissions");
    if permissions_dir.exists() {
        // Only removes the directory when empty; preserves any manual permissions if ever added.
        let _ = std::fs::remove_dir(permissions_dir);
    }
    tauri_build::build()
}
